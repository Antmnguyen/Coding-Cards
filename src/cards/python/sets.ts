import { topic } from "../topic";

export const sets = topic("python", "sets", [
  {
    id: "set-empty",
    prompt: "Declare an empty set `seen`",
    solution: "seen = set()",
    explain: "{} is an empty DICT, not a set.",
    check: "seen == set() and type(seen) is set",
  },
  {
    id: "set-add",
    prompt: "Add `x` to set `seen`",
    solution: "seen.add(x)",
    explain: ".add, not .append.",
    setup: "seen = set(); x = 1",
    check: "seen == {1}",
  },
  {
    id: "set-discard",
    prompt: "Remove `x` from set `s` without raising if it is missing",
    solution: "s.discard(x)",
    explain: "remove(x) raises KeyError when x is missing; discard does not.",
  },
  {
    id: "set-add-list",
    prompt: "Add list `path` to set `result` in a hashable form",
    solution: "result.add(tuple(path))",
    explain: "Lists cannot go in a set; tuples can, and tuple() already copies.",
    setup: "result = set(); path = [1, 2]",
    check: "result == {(1, 2)}",
  },
  {
    id: "set-from-list",
    prompt: "Unique items of list `a`, as a set",
    solution: "set(a)",
    explain: "set() takes any iterable.",
    setup: "a = [1, 1, 2]",
    check: "_ == {1, 2} and type(_) is set",
  },
  {
    id: "set-not-in",
    prompt: "Condition: `x` is not in `seen`",
    solution: "x not in seen",
    explain: "Lowercase `not in`, as one operator.",
    setup: "seen = {1}; x = 2",
    check: "_ is True",
  },
  {
    id: "set-intersection",
    prompt: "Items in both set `a` and set `b`",
    solution: "a & b",
    accepted: ["a.intersection(b)"],
    explain: "& is intersection, | is union, - is difference.",
    setup: "a = {1, 2}; b = {2, 3}",
    check: "_ == {2}",
  },
  {
    id: "set-union",
    prompt: "Items in set `a` or set `b`",
    solution: "a | b",
    accepted: ["a.union(b)"],
    explain: "Sets do not support +; use |.",
    setup: "a = {1, 2}; b = {2, 3}",
    check: "_ == {1, 2, 3}",
  },
  {
    id: "set-to-lists",
    prompt: "Turn set of tuples `result` into a list of lists",
    solution: "[list(t) for t in result]",
    explain: "Convert each tuple back with list().",
    setup: "result = {(1, 2)}",
    check: "_ == [[1, 2]]",
  },
]);
