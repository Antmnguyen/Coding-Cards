import { topic } from "../topic";

export const lists = topic("python", "lists", [
  {
    id: "list-append",
    expect: "a becomes [1, 2, 3]",
    prompt: "`a` is a list. Add `x` to the end of it.",
    setup: "a = [1, 2]\nx = 3",
    solution: "a.append(x)",
    explain: "append takes exactly one argument and returns None.",
    check: "a == [1, 2, 3]",
  },
  {
    id: "list-pop-last",
    expect: "gives 3, and a becomes [1, 2]",
    prompt: "`a` is a list. Remove its last item and get that item back.",
    setup: "a = [1, 2, 3]",
    solution: "a.pop()",
    explain: "pop() with no index is O(1); pop(0) is O(n).",
    check: "_ == 3 and a == [1, 2]",
  },
  {
    id: "list-insert",
    expect: "a becomes [1, 9, 2, 3]",
    prompt: "`a` is a list. Insert the value `val` at index `i`, pushing the rest to the right.",
    setup: "a = [1, 2, 3]\ni = 1\nval = 9",
    solution: "a.insert(i, val)",
    explain: "insert(index, value): index first, and it shifts the rest right.",
    check: "a == [1, 9, 2, 3]",
  },
  {
    id: "list-last",
    expect: "gives 3",
    prompt: "`a` is a list. Get its last item without removing it.",
    setup: "a = [1, 2, 3]",
    solution: "a[-1]",
    explain: "Negative indexes count from the end.",
    check: "_ == 3",
  },
  {
    id: "list-copy",
    expect: "gives a new list [1, 2]",
    prompt: "`path` is a list. Make a separate copy of it, so later changes to `path` do not affect the copy.",
    setup: "path = [1, 2]",
    solution: "path[:]",
    accepted: ["list(path)", "path.copy()"],
    explain: "Appending plain `path` stores a reference that later pops will empty.",
    check: "_ == path and _ is not path",
  },
  {
    id: "list-sorted",
    expect: "res is [1, 2, 3], and nums stays [3, 1, 2]",
    prompt: "`nums` is an unsorted list. Store a sorted copy in a new variable `res`, leaving `nums` unchanged.",
    setup: "nums = [3, 1, 2]",
    solution: "res = sorted(nums)",
    explain: "nums.sort() sorts in place and returns None.",
    check: "res == [1, 2, 3] and nums == [3, 1, 2]",
  },
  {
    id: "list-sort-desc",
    expect: "a becomes [3, 2, 1]",
    prompt: "`a` is a list of numbers. Sort it in place, largest first.",
    setup: "a = [1, 3, 2]",
    solution: "a.sort(reverse=True)",
    explain: "reverse=True is a keyword argument, capital T.",
    check: "a == [3, 2, 1]",
  },
  {
    id: "list-zeros",
    expect: "gives [0, 0, 0]",
    prompt: "`n` is an int. Make a list containing `n` zeros.",
    setup: "n = 3",
    solution: "[0] * n",
    explain: "Safe for immutables like ints; not for nested lists.",
    check: "_ == [0, 0, 0]",
  },
  {
    id: "list-grid",
    expect: "grid is [[0, 0, 0], [0, 0, 0]]",
    prompt:
      "`rows` and `cols` are ints. Create `grid`, a 2D list of zeros with `rows` rows and `cols` columns, where every row is its own list.",
    setup: "rows = 2\ncols = 3",
    solution: "grid = [[0] * cols for _ in range(rows)]",
    explain: "[[0] * cols] * rows repeats the SAME row object, so one write changes every row.",
    check: "grid == [[0, 0, 0], [0, 0, 0]] and grid[0] is not grid[1]",
  },
  {
    id: "list-comp-squares",
    expect: "gives [1, 4, 9]",
    prompt: "`a` is a list of numbers. Build a new list with every item squared. Call each item `x`.",
    setup: "a = [1, 2, 3]",
    solution: "[x * x for x in a]",
    accepted: ["[x ** 2 for x in a]"],
    explain: "Comprehension: [expr for item in iterable].",
    check: "_ == [1, 4, 9]",
  },
]);
